            f"За последние шесть месяцев команда заработала {_fmt_money(six_m)} "
            f"долларов призовых. Этот показатель подтверждает, что организация "
            f"движется в правильном направлении и стабильно конкурентоспособна. "
            f"Призовые обеспечивают как материальную базу для дальнейшего развития, "
            f"так и репутационный рост, привлекая внимание спонсоров и партнёров."
