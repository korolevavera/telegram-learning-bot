def _build_team_bio(info: dict) -> str:
    name = info.get("name") or "Команда"
    acronym = info.get("acronym")
    country = _RU_COUNTRIES.get(info.get("country_code")) or info.get("country_name")
    country_name = info.get("country_name")
    est = info.get("est_date")
    stats = info.get("stats") or {}
    roster = info.get("roster") or []
    achievements = info.get("achievements") or []
    matches_list = info.get("matches") or []

    out: list[str] = []

    full_name = f"{name} ({acronym})" if acronym and acronym not in name else name
    lead = (
        f"«{full_name}» — профессиональная киберспортивная команда по Counter-Strike 2, "
        f"представляющая соревновательную сцену."
    )
    if country and country_name:
        lead += f" Коллектив ассоциируется со сценой {country}."
    if est:
        lead += f" История организации ведётся с {str(est)[:4]} года."
    _push(out, lead)

    _push(out, (
        f"Команда «{name}» сложилась как единый организм из игроков с разным "
        f"бэкграундом, но единым стремлением — быть среди лучших. Внутри коллектива "
        f"выстроена чёткая структура: каждый участник закрывает свою роль, а "
        f"сыгранность рождается на ежедневных тренировках, совместных разборах и "
        f"долгих часах работы над общими таймингами. Именно эта сплочённость "
        f"позволяет показывать результат, превосходящий сумму индивидуальных "
        f"навыков каждого игрока по отдельности."
    ))

    if country_name:
        _push(out, (
            f"«{name}» представляет киберспортивную сцену {country_name}. Выступая под "
            f"флагом своей страны, команда несёт ответственность перед болельщиками и "
            f"вносит вклад в развитие регионального киберспорта. Успехи коллектива "
            f"вдохновляют молодых игроков и укрепляют репутацию местной сцены на "
            f"международной арене, где с каждым годом конкуренция только растёт."
        ))

    if est:
        year = str(est)[:4]
        _push(out, (
            f"За годы существования «{name}» прошла путь от становления до "
            f"конкурентоспособного коллектива. С момента основания в {year} команда "
            f"проходила через множество изменений: смены составов, тренерских штабов "
            f"и игровых подходов. Однако постоянным оставалось главное — стремление "
            f"к результату и готовность вкладывать силы в развитие, что в "
            f"совокупности и формирует лицо организации, которое знают болельщики."
        ))

    _push(out, _team_structure_paragraph(name, roster))

    out.extend(_team_stats_paragraphs(name, stats))

    if matches_list:
        wins = sum(1 for m in matches_list if m.get("result") == "win")
        losses = sum(1 for m in matches_list if m.get("result") == "loss")
        _push(out, (
            f"За последний период команда провела {len(matches_list)} матчей, "
            f"в {wins} из которых добилась победы"
            + (f", потерпев {losses} поражений" if losses else "")
            + ". Каждая сыгранная серия — это ценный опыт, который команда "
            "внимательно разбирает: сильные стороны закрепляются, слабые — "
            "прорабатываются на тренировках перед следующим турниром."
        ))
        top_event = next(
            (m.get("event") for m in matches_list if m.get("tier") in ("S", "A") and m.get("event")), None
        )
        if top_event:
            _push(out, (
                f"Среди соперников команды в этот период были коллективы уровня "
                f"«{top_event}». Встречи с такими оппонентами — важнейшая проверка для "
                f"«{name}»: они позволяют оценить реальный уровень организации, "
                f"выявить пробелы в игре и понять, над чем нужно работать перед "
                f"более крупными турнирами."
            ))

