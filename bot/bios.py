def _plural(n: int, one: str, few: str, many: str) -> str:
    n10, n100 = n % 10, n % 100
    if n10 == 1 and n100 != 11:
        return one
    if 2 <= n10 <= 4 and not (12 <= n100 <= 14):
        return few
    return many


def _fmt_date(value: Any) -> str | None:
    text = str(value or "")[:10]
    if len(text) != 10:
        return None
    try:
        d = datetime.strptime(text, "%Y-%m-%d")
    except ValueError:
        return None
    return f"{d.day} {_RU_MONTHS[d.month]} {d.year} года"


def _fmt_money(value: Any) -> str:
    try:
        return f"{int(float(value)):,}".replace(",", " ")
    except (TypeError, ValueError):
        return ""


def _prep(p: dict) -> dict:
    nickname = p.get("nickname") or p.get("name") or "игрок"
    real = " ".join(filter(None, (p.get("first_name"), p.get("last_name"))))
    country = _RU_COUNTRIES.get(p.get("country_code")) or p.get("country_name")
    role = p.get("role")
    team = p.get("team") or p.get("team_name")
    region = p.get("region")
    birthday = p.get("birthday")
    age = p.get("age")
    aliases = p.get("aliases") or []
    tags = p.get("tags") or []
    return {
        "nickname": nickname,
        "real": real,
        "country": country,
        "role": role,
        "team": team,
        "region": region,
        "birthday": birthday,
        "age": age,
        "aliases": aliases,
        "tags": tags,
    }


