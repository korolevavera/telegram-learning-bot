def _team_roster_deep(name: str, roster: list) -> list[str]:
    out = []
    non_coach = [r for r in roster if not r.get("is_coach")]
    if len(non_coach) >= 2:
        _push(out, (
            f"Каждый игрок «{name}» вносит в коллектив нечто большее, чем просто "
            f"статистику. Слаженность команды строится на взаимопонимании, которое "
            f"нельзя измерить цифрами: умение предугадать действия напарника, "
            f"поддержать его в нужный момент и вместе выйти из сложной ситуации. "
            f"Внутри «{name}» отработаны игровые связки и стандарты, позволяющие "
            f"действовать быстро и без лишних слов даже в самых хаотичных раундах. "
            f"Эта химия между игроками — то самое невидимое преимущество, которое "
            f"часто решает исход напряжённых серий."
        ))
    if len(non_coach) >= 3:
        rated = [(r.get("nickname") or "игрок", r.get("rating")) for r in non_coach if r.get("rating") is not None]
        if rated:
            rated_txt = ", ".join(f"{n} — {r}" for n, r in sorted(rated, key=lambda x: -x[1]))
            _push(out, (
                f"По индивидуальным показателям состава видно, что «{name}» строится "
                f"вокруг сильных исполнителей: {rated_txt}. Рейтинг отдельных игроков "
                f"в совокупности с командной игрой создаёт основу, на которой тренерский "
                f"штаб выстраивает тактические планы под каждого конкретного соперника. "
                f"Сочетание персонального мастерства и командной дисциплины — залог "
                f"стабильности организации в долгосрочной перспективе."
            ))
    return out


def _team_achievement_detail(name: str, achievements: list) -> list[str]:
    out = []
    won = [a for a in achievements if (a.get("title") or "").lower() == "winner"]
    if won:
        for a in won[:3]:
            tr = a.get("tournament") or "крупном турнире"
            date = (a.get("date") or "")[:4]
            date_txt = f" в {date} году" if date else ""
            prize = _fmt_money(a.get("prize"))
            prize_txt = f" и призовым фондом в {prize} долларов" if prize else ""
            _push(out, (
                f"Один из знаковых моментов в истории «{name}» — победа{date_txt} на "
                f"турнире «{tr}»{prize_txt}. Подобные триумфы становятся точками отсчёта "
                f"для команды: они доказывают, что выбранная стратегия развития "
                f"работает, и задают вектор на будущее. Атмосфера финального дня, "
                f"напряжение решающей карты и радость долгожданного успеха — те "
                f"моменты, ради которых команда и существует."
            ))
    return out


