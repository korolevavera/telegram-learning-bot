def _faceit_stats_paragraphs(nickname: str, stats: dict, elo) -> list[str]:
    out = []
    matches = stats.get("matches")
    wins = stats.get("wins")
    losses = stats.get("losses")
    winrate = stats.get("winrate")

    if matches is not None:
        text = f"За время игры {nickname} провёл {matches} матчей"
        if wins is not None and losses is not None:
            text += f", из которых выиграл {wins} и проиграл {losses}"
        if winrate is not None:
            text += f" (общий винрейт {winrate}%)"
        text += (
            ". Столь внушительная выборка матчей — это большой объём практического "
            "опыта, который невозможно заменить ничем другим: каждый матч учит "
            "новому, оттачивает реакцию и расширяет понимание игры."
        )
        _push(out, text)

    if elo is not None:
        _push(out, (
            f"Рейтинг ELO {nickname} находится на отметке {elo}. ELO на FACEIT — "
            f"это живой показатель уровня: он растёт только через победы над "
            f"равными и более сильными соперниками. Высокий ELO означает, что "
            f"игрок последовательно обыгрывает конкурентное окружение и "
            f"действительно заслуживает места среди сильнейших рейтинговых "
            f"игроков своего региона."
        ))

    if stats.get("kd") is not None:
        _push(out, (
            f"Соотношение фрагов и смертей у {nickname} — {stats['kd']}, что "
            f"{_kd_line(stats['kd'])}. Эффективный K/D в рейтинговых матчах — "
            f"фундамент успешной игры: он позволяет игроку не только удерживать "
            f"положительный баланс, но и влиять на исход раундов, доминируя в "
            f"дуэлях и создавая преимущество для команды."
        ))
    if stats.get("kills") is not None:
        _push(out, (
            f"Суммарно {nickname} оформил {stats['kills']} фрагов. За этой цифрой — "
            f"тысячи сыгранных раундов и постоянный контроль над огневой дистанцией. "
            f"Количество фрагов в совокупности с остальной статистикой говорит о "
            f"том, что {nickname} не отсиживается в тылу, а активно участвует в "
            f"боевых действиях на протяжении всей карьеры."
        ))
    if stats.get("hs") is not None:
        _push(out, (
            f"Точность попаданий в голову у {nickname} — {stats['hs']}%, что говорит "
            f"о хорошо поставленной механике и умении выигрывать дуэли чисто. "
            f"Высокий процент попаданий в голову сокращает время размена и делает "
            f"игрока особенно опасным в открытых перестрелках и клатчах один на один."
        ))
    if stats.get("adr") is not None:
        _push(out, (
            f"Средний урон за раунд (ADR) — {stats['adr']}. Игрок постоянно давит на "
            f"соперника, набирая стабильный урон даже в проигранных раундах. Высокий "
            f"ADR — маркер активной и агрессивной игры, которая создаёт давление "
            f"и переводит инициативу в руки команды {nickname}."
        ))
    if stats.get("win_streak"):
        _push(out, (
            f"В настоящий момент у {nickname} серия из {stats['win_streak']} побед "
            f"подряд. Серии побед — лучший показатель текущей формы: они говорят о "
            f"том, что игрок находится в отличном состоянии, уверенно справляется с "
            f"соперниками и сохраняет высокую концентрацию от матча к матчу."
        ))
    if stats.get("longest_streak"):
        _push(out, (
            f"Лучшая серия побед в его карьере на платформе составила "
            f"{stats['longest_streak']} матчей подряд, что говорит о способности "
            f"долго держать высокий уровень. Такие отрезки складываются не только "
            f"из таланта, но и из умения сохранять ментальную стабильность на "
            f"протяжении серии напряжённых игр."
        ))
    return out


def _kd_line(kd: float) -> str:
    if kd >= 1.3:
        return "является явно выраженным показателем доминирования на платформе"
    if kd >= 1.1:
        return "заметно выше среднего уровня по платформе"
    return "находится на стабильном, характерном для командного игрока уровне"


def _words_count(text: str) -> int:
    return len([w for w in text.split() if w.strip()])


