def _td(kd: float) -> str:
    if kd >= 1.3:
        return "выдающийся показатель даже для профессиональной сцены"
    if kd >= 1.1:
        return "высокий показатель, заметно выше среднего уровня"
    return "уверенный показатель, характерный для грамотного командного игрока"


