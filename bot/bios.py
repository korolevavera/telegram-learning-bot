def _career_sections(p: dict, nickname: str) -> str:
    timeline = p.get("teams") or []
    if not timeline:
        team = p.get("team")
        if team:
            return (
                f"Профессиональная карьера {nickname} на данном этапе связана с командой "
                f"«{team}». Именно в её составе он продолжает оттачивать мастерство, "
                f"выступая на турнирах и развивая командную химию с партнёрами. "
                f"Каждый сыгранный матч — это новый опыт, который постепенно "
                f"превращает перспективного исполнителя в зрелого профессионала."
            )
        return (
            f"О карьере {nickname} известно, что она строилась постепенно, через "
            f"череду команд и этапов. Подобный путь характерен для большинства "
            f"профессиональных игроков: взлёты сменяются спадами, смены составов "
            f"открывают новые возможности, а опыт, накопленный за годы, позволяет "
            f"сохранять стабильность в самых сложных турнирных сериях."
        )

    dedup = []
    for t in timeline:
        if dedup and dedup[-1].get("team") == t.get("team"):
            dedup[-1] = t
        else:
            dedup.append(t)
    timeline = dedup

    first = timeline[0]
    if first.get("date"):
        start = f"Профессиональную карьеру {nickname} начал в {str(first['date'])[:4]} году"
    else:
        start = f"Профессиональный этап карьеры {nickname} начался с первых командных составов"
    if first.get("team"):
        start += f" в составе коллектива «{first['team']}»"
    start += (
        ". Уже на этом этапе проявились базовые качества игрока: уверенная механика, "
        "понимание таймингов и первое чувство командной игры, которые впоследствии "
        f"стали визитной карточкой {nickname}."
    )
    return start


