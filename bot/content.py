def flatten_tactics(map_id: str) -> list[dict]:
    """Приводит тактики карты к плоскому списку (для бота)."""
    data = TACTICS.get(map_id)
    if data is None:
        return []
    if isinstance(data, dict):
        out: list[dict] = []
        for side in ("t", "ct"):
            rounds = data.get(side, {})
            for round_key in ("pistol", "eco", "force", "full"):
                for tactic in rounds.get(round_key, []):
                    out.append(tactic)
        return out
    return list(data)


def tactic_steps(tactic: dict) -> list[str]:
    """Возвращает плоский список шагов тактики (учитывает фазы)."""
    def _text(s):
        return s.get("text") if isinstance(s, dict) else s

    phases = tactic.get("phases")
    if phases:
        return [_text(step) for phase in phases for step in phase.get("steps", [])]
    return [_text(step) for step in tactic.get("steps", [])]


